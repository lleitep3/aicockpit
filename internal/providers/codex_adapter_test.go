func TestCodexCompiler_CompileSkills(t *testing.T) {
	compiler := NewCodexCompiler()
	provider := codexProvider(map[string]*FeatureConfig{
		"skills": {Enabled: true, Path: ".agents/skills"},
	})

	files, err := compiler.CompileSkills([]CanonicalSkill{
		{
			Name:        "release",
			Description: "Release helper",
			Content:     "Use the release checklist.",
			ScriptFiles: map[string]string{"scripts/z.sh": "z", "scripts/a.sh": "a"},
		},
		{Name: "review", Description: "Review helper", Content: "Review the diff."},
	}, provider)
	if err != nil {
		t.Fatalf("CompileSkills() error = %v", err)
	}

	releasePath := filepath.Join(".agents/skills", "release", "SKILL.md")
	release, ok := files[releasePath]
	if !ok {
		t.Fatalf("missing %s in %#v", releasePath, files)
	}
	if !strings.HasPrefix(release, "---\n") {
		t.Fatalf("skill frontmatter was not kept first: %q", release)
	}
	if !strings.Contains(release, "name: \"release\"") || !strings.Contains(release, "Use the release checklist.") {
		t.Errorf("unexpected compiled skill: %q", release)
	}
	if !strings.Contains(release, "<!-- GENERATED by AICockpit codex adapter") {
		t.Errorf("generated header missing from skill: %q", release)
	}
	if got := files[filepath.Join(".agents/skills", "release", "scripts", "a.sh")]; got != "a" {
		t.Errorf("a.sh = %q, want %q", got, "a")
	}
	if got := files[filepath.Join(".agents/skills", "release", "scripts", "z.sh")]; got != "z" {
		t.Errorf("z.sh = %q, want %q", got, "z")
	}
	if _, ok := files[filepath.Join(".agents/skills", "review", "SKILL.md")]; !ok {
		t.Error("second skill was not compiled")
	}

	tests := []struct {
		name  string
		skill CanonicalSkill
	}{
		{name: "invalid skill name", skill: CanonicalSkill{Name: "../release"}},
		{
			name: "script escapes skill directory",
			skill: CanonicalSkill{
				Name:        "release",
				ScriptFiles: map[string]string{"../outside.sh": "unsafe"},
			},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if _, err := compiler.CompileSkills([]CanonicalSkill{tt.skill}, provider); err == nil {
				t.Error("CompileSkills() expected validation error")
			}
		})
	}
}

