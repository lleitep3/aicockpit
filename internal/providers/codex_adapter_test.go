func TestCodexCompiler_CompilePermissions(t *testing.T) {
	compiler := NewCodexCompiler()
	provider := codexProvider(map[string]*FeatureConfig{
		"permissions": {Enabled: true, Path: ".codex/rules"},
	})

	files, err := compiler.CompilePermissions(&CanonicalPermissions{
		AllowedCommands: []string{"git status", "git status", "make"},
		DeniedCommands:  []string{"rm -rf"},
		AllowedDirs:     []string{"src"},
		Allow:           []string{"Exec(go test ./...)", "Read(src/**)"},
		Deny:            []string{"Exec(rm -rf build)"},
		Ask:             []string{"Exec(git push)", "network"},
	}, provider)
	if err != nil {
		t.Fatalf("CompilePermissions() error = %v", err)
	}

	path := filepath.Join(".codex/rules", "aicockpit.rules")
	content, ok := files[path]
	if !ok {
		t.Fatalf("missing %s in %#v", path, files)
	}
	for _, expected := range []string{
		"# GENERATED by AICockpit .rules adapter",
		`pattern = ["git", "status"]`,
		`decision = "allow"`,
		`pattern = ["rm", "-rf"]`,
		`decision = "forbidden"`,
		`pattern = ["go", "test", "./..."]`,
		`pattern = ["git", "push"]`,
		`decision = "prompt"`,
		"allowed_dirs requires Codex sandbox configuration",
		`allow entry "Read(src/**)" is not a Codex command`,
		`ask entry "network" is not a Codex command`,
	} {
		if !strings.Contains(content, expected) {
			t.Errorf("permission content does not contain %q: %s", expected, content)
		}
	}
	if got := strings.Count(content, `pattern = ["git", "status"]`); got != 1 {
		t.Errorf("duplicate allow rule count = %d, want 1", got)
	}

	tests := []struct {
		name     string
		perms    *CanonicalPermissions
		provider *Provider
		wantLen  int
	}{
		{name: "nil permissions", perms: nil, provider: provider, wantLen: 0},
		{name: "empty permissions", perms: &CanonicalPermissions{}, provider: provider, wantLen: 0},
		{
			name:     "warnings without rules",
			perms:    &CanonicalPermissions{AllowedDirs: []string{"src"}},
			provider: provider,
			wantLen:  1,
		},
		{
			name: "invalid quoted command",
			perms: &CanonicalPermissions{
				AllowedCommands: []string{`echo "unfinished`},
			},
			provider: provider,
			wantLen:  -1,
		},
		{
			name: "file path already has rules extension",
			perms: &CanonicalPermissions{
				AllowedCommands: []string{"go"},
			},
			provider: codexProvider(map[string]*FeatureConfig{
				"permissions": {Enabled: true, Path: ".codex/custom.rules"},
			}),
			wantLen: 1,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			files, err := compiler.CompilePermissions(tt.perms, tt.provider)
			if tt.wantLen < 0 {
				if err == nil || !strings.Contains(err.Error(), "invalid Codex permission command") {
					t.Fatalf("CompilePermissions() error = %v, want invalid command error", err)
				}
				return
			}
			if err != nil {
				t.Fatalf("CompilePermissions() error = %v", err)
			}
			if len(files) != tt.wantLen {
				t.Errorf("CompilePermissions() returned %d files, want %d", len(files), tt.wantLen)
			}
			if tt.name == "file path already has rules extension" {
				if _, ok := files[".codex/custom.rules"]; !ok {
					t.Errorf("expected direct .rules path in %#v", files)
				}
			}
		})
	}
}

