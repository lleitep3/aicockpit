func TestCodexCompiler_CompileEntrypoint(t *testing.T) {
	compiler := NewCodexCompiler()
	provider := codexProvider(map[string]*FeatureConfig{
		"rules": {Enabled: true, Path: "AGENTS.md"},
	})

	tests := []struct {
		name       string
		entrypoint *CanonicalEntrypoint
		wantErr    string
		want       string
	}{
		{
			name: "context and golden rules",
			entrypoint: &CanonicalEntrypoint{
				ProjectContext: "Project context",
				GoldenRules:    []string{" first rule ", "", "second rule"},
			},
			want: "Project context\n\n## AICockpit Gold Rules\n\nfirst rule\n\nsecond rule",
		},
		{
			name:       "empty entrypoint still creates target",
			entrypoint: &CanonicalEntrypoint{},
			want:       "",
		},
		{
			name:       "nil entrypoint",
			entrypoint: nil,
			wantErr:    "entrypoint cannot be nil",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			files, err := compiler.CompileEntrypoint(tt.entrypoint, provider)
			if tt.wantErr != "" {
				if err == nil || !strings.Contains(err.Error(), tt.wantErr) {
					t.Fatalf("CompileEntrypoint() error = %v, want substring %q", err, tt.wantErr)
				}
				return
			}
			if err != nil {
				t.Fatalf("CompileEntrypoint() error = %v", err)
			}
			got, ok := files["AGENTS.md"]
			if !ok {
				t.Fatalf("CompileEntrypoint() did not create AGENTS.md: %#v", files)
			}
			if !strings.Contains(got, "<!-- GENERATED by AICockpit codex adapter") {
				t.Errorf("generated header missing from %q", got)
			}
			if !strings.Contains(got, tt.want) {
				t.Errorf("compiled content = %q, want it to contain %q", got, tt.want)
			}
		})
	}
}

