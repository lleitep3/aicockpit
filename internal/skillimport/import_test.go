func TestImportLocalRejectsOverlappingOrExistingReviewDirectory(t *testing.T) {
	root := t.TempDir()
	source := filepath.Join(root, "source")
	target := filepath.Join(root, "cockpit-skills")
	writeSkillFile(t, source, "SKILL.md", "---\nname: skill\ndescription: Skill\n---\nBody.\n", 0o644)

	if _, err := ImportLocalWithConflictArchive(source, target, filepath.Join(target, "review"), true); err == nil {
		t.Fatal("expected review directory inside canonical library to be rejected")
	}
	existingReview := filepath.Join(root, "existing-review")
	if err := os.Mkdir(existingReview, 0o700); err != nil {
		t.Fatalf("create existing review directory: %v", err)
	}
	if _, err := ImportLocalWithConflictArchive(source, target, existingReview, true); err == nil {
		t.Fatal("expected existing review directory to be rejected")
	}
}

