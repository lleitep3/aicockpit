func TestImportLocalPreservesMetadataResourcesAndExecutableMode(t *testing.T) {
	root := t.TempDir()
	source := filepath.Join(root, "copilot", "skills", "reviewer")
	target := filepath.Join(root, ".cockpit", "skills")
	writeSkillFile(t, source, "SKILL.md", "---\nname: reviewer\ndescription: Review code\nallowed-tools:\n  - git\n  - read\nmetadata:\n  source: copilot\n---\nReview carefully.\n", 0o644)
	writeSkillFile(t, source, "references/checklist.md", "Check the diff.\n", 0o644)
	writeSkillFile(t, source, "scripts/check.sh", "#!/bin/sh\necho check\n", 0o755)

	report, err := ImportLocal(filepath.Dir(source), target, false)
	if err != nil {
		t.Fatalf("ImportLocal() error = %v", err)
	}
	if len(report.Items) != 1 || report.Items[0].Status != "imported" {
		t.Fatalf("ImportLocal() items = %#v, want one imported skill", report.Items)
	}

	for _, rel := range []string{"SKILL.md", "references/checklist.md", "scripts/check.sh"} {
		original, err := os.ReadFile(filepath.Join(source, rel))
		if err != nil {
			t.Fatalf("read source %s: %v", rel, err)
		}
		got, err := os.ReadFile(filepath.Join(target, "reviewer", rel))
		if err != nil {
			t.Fatalf("read imported %s: %v", rel, err)
		}
		if string(got) != string(original) {
			t.Errorf("imported %s differs from source", rel)
		}
	}
	info, err := os.Stat(filepath.Join(target, "reviewer", "scripts", "check.sh"))
	if err != nil {
		t.Fatalf("stat imported script: %v", err)
	}
	if got := info.Mode().Perm(); got != 0o755 {
		t.Errorf("imported script mode = %o, want 755", got)
	}
}

func TestImportLocalSkipsUnchangedAndReportsConflicts(t *testing.T) {
	root := t.TempDir()
	source := filepath.Join(root, "copilot-skills")
	target := filepath.Join(root, "cockpit-skills")
	writeSkillFile(t, source, "already/SKILL.md", "---\nname: already\ndescription: Same\n---\nSame body.\n", 0o644)
	writeSkillFile(t, source, "conflict/SKILL.md", "---\nname: conflict\ndescription: Incoming\n---\nIncoming body.\n", 0o644)
	writeSkillFile(t, source, "fresh/SKILL.md", "---\nname: fresh\ndescription: New\n---\nNew body.\n", 0o644)
	writeSkillFile(t, target, "already/SKILL.md", "---\nname: already\ndescription: Same\n---\nSame body.\n", 0o644)
	writeSkillFile(t, target, "conflict/SKILL.md", "---\nname: conflict\ndescription: Existing\n---\nExisting body.\n", 0o644)

	report, err := ImportLocal(source, target, false)
	if err != nil {
		t.Fatalf("ImportLocal() error = %v", err)
	}
	gotStatuses := make(map[string]string)
	for _, item := range report.Items {
		gotStatuses[item.Name] = item.Status
	}
	for name, want := range map[string]string{"already": "unchanged", "conflict": "conflict", "fresh": "imported"} {
		if gotStatuses[name] != want {
			t.Errorf("skill %q status = %q, want %q", name, gotStatuses[name], want)
		}
	}
	conflictContent, err := os.ReadFile(filepath.Join(target, "conflict", "SKILL.md"))
	if err != nil {
		t.Fatalf("read existing conflicting skill: %v", err)
	}
	if !strings.Contains(string(conflictContent), "Existing body.") {
		t.Fatalf("existing conflicting skill was modified: %s", conflictContent)
	}

	report, err = ImportLocal(source, target, false)
	if err != nil {
		t.Fatalf("second ImportLocal() error = %v", err)
	}
	for _, item := range report.Items {
		if item.Name == "fresh" && item.Status != "unchanged" {
			t.Errorf("second import status for fresh skill = %q, want unchanged", item.Status)
		}
	}
}

