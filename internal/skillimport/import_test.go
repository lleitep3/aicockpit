func TestImportLocalSavesConflictsOutsideCanonicalLibrary(t *testing.T) {
	root := t.TempDir()
	source := filepath.Join(root, "copilot-skills")
	target := filepath.Join(root, "cockpit-skills")
	review := filepath.Join(root, "review", "copilot-local")
	writeSkillFile(t, source, "reviewer/SKILL.md", "---\nname: reviewer\ndescription: Local version\n---\nLocal body.\n", 0o644)
	writeSkillFile(t, source, "reviewer/scripts/check.sh", "#!/bin/sh\necho local\n", 0o755)
	writeSkillFile(t, source, "occupied/SKILL.md", "---\nname: another-skill\ndescription: Local version\n---\nAnother local body.\n", 0o644)
	writeSkillFile(t, target, "reviewer/SKILL.md", "---\nname: reviewer\ndescription: Canonical version\n---\nCanonical body.\n", 0o644)
	writeSkillFile(t, target, "occupied/SKILL.md", "---\nname: different-skill\ndescription: Existing occupant\n---\nOccupant body.\n", 0o644)

	report, err := ImportLocalWithConflictArchive(source, target, review, false)
	if err != nil {
		t.Fatalf("ImportLocalWithConflictArchive() error = %v", err)
	}
	if len(report.Items) != 2 {
		t.Fatalf("report items = %#v, want two saved conflicts", report.Items)
	}
	for _, item := range report.Items {
		if item.Status != "saved-conflict" {
			t.Errorf("skill %q status = %q, want saved-conflict", item.Name, item.Status)
		}
	}
	if report.ReviewTarget != review {
		t.Errorf("review target = %q, want %q", report.ReviewTarget, review)
	}
	localCopy, err := os.ReadFile(filepath.Join(review, "reviewer", "SKILL.md"))
	if err != nil {
		t.Fatalf("read saved local version: %v", err)
	}
	if !strings.Contains(string(localCopy), "Local body.") {
		t.Errorf("saved copy does not contain local version: %s", localCopy)
	}
	canonical, err := os.ReadFile(filepath.Join(target, "reviewer", "SKILL.md"))
	if err != nil {
		t.Fatalf("read canonical version: %v", err)
	}
	if !strings.Contains(string(canonical), "Canonical body.") {
		t.Errorf("canonical version changed: %s", canonical)
	}
	occupiedCopy, err := os.ReadFile(filepath.Join(review, "occupied", "SKILL.md"))
	if err != nil {
		t.Fatalf("read saved directory-collision skill: %v", err)
	}
	if !strings.Contains(string(occupiedCopy), "Another local body.") {
		t.Errorf("saved directory-collision copy is wrong: %s", occupiedCopy)
	}
	info, err := os.Stat(filepath.Join(review, "reviewer", "scripts", "check.sh"))
	if err != nil {
		t.Fatalf("stat saved script: %v", err)
	}
	if got := info.Mode().Perm(); got != 0o755 {
		t.Errorf("saved script mode = %o, want 755", got)
	}
}

